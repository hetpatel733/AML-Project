@app.post("/predict", response_model=PredictResponse, status_code=status.HTTP_200_OK, tags=["Inference"])
def predict_news(payload: PredictRequest):
    """
    Classify news article text into 'FAKE' or 'REAL' using the trained NLP model.
    Includes real-time Gemini AI credibility insights when API key is configured.
    """
    try:
        if not payload.text or len(payload.text.strip()) < 5:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Article text body must be at least 5 characters long."
            )

        result = predictor.predict(
            text=(payload.title or "") + " " + payload.text,
            model_name=payload.model,
            dataset=payload.dataset
        )
        combined_text = ((payload.title or "") + " " + payload.text).strip()
        result["wordCount"] = len(combined_text.split())
        result["charCount"] = len(combined_text)
        result["topTokens"] = []
        result["explanation"] = "Prediction generated by the selected trained model."
        
        # Enhance with Gemini AI insights
        gemini_insights = gemini_service.analyze_news_article(
            title=payload.title or "",
            text=payload.text,
            prediction=result["prediction"],
            confidence=result["confidence"]
        )
        result["geminiInsights"] = gemini_insights
        
        return result
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Inference error: {str(exc)}"
        )


@app.post("/predict/all", status_code=status.HTTP_200_OK, tags=["Inference"])
def predict_all_models(payload: PredictRequest):
    """
    Run full multi-model simulation across the four trained candidate models and 2 ensemble architectures.
    Includes real-time Gemini AI credibility insights when API key is configured.
    """
    try:
        if not payload.text or len(payload.text.strip()) < 5:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Article text body must be at least 5 characters long."
            )

        result = predictor.predict_all(
            text=payload.text,
            title=payload.title or "",
            dataset=payload.dataset
        )
        
        # Enhance with Gemini AI insights using soft ensemble prediction
        soft_ensemble = result.get("ensembles", {}).get("weighted_soft_ensemble", {})
        gemini_insights = gemini_service.analyze_news_article(
            title=payload.title or "",
            text=payload.text,
            prediction=soft_ensemble.get("prediction", "REAL"),
            confidence=soft_ensemble.get("confidence", 0.5)
        )
        result["geminiInsights"] = gemini_insights
        
        return result
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Multi-model simulation error: {str(exc)}"
        )


@app.get("/experiment-metadata", status_code=status.HTTP_200_OK, tags=["Experiments"])
def get_experiment_metadata(dataset: str = "isot"):
    """
    Returns full experimental dataset metrics, 5-fold CV scores, validation weights, and test benchmarks.
    """
    import json
    from src.config import RESULTS_DIR

    metadata_path = RESULTS_DIR / dataset / "benchmark.json"
    if not metadata_path.exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Experiment metadata file for dataset {dataset} has not been generated yet."
        )
    with open(metadata_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data


