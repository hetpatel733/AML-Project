# Pydantic Schemas for Request & Response validation
class PredictRequest(BaseModel):
    title: Optional[str] = Field(
        default="",
        description="Headline or title of the news article",
        examples=["Senate approves bipartisan clean energy infrastructure investment package"]
    )
    text: str = Field(
        ...,
        min_length=5,
        description="Full text body or excerpt of the news article",
        examples=["WASHINGTON (Reuters) - Lawmakers passed comprehensive legislation allocating billions to grid upgrades after committee debate."]
    )
    model: Optional[str] = Field(
        default=None,
        description="Optional model override: 'logistic_regression', 'naive_bayes', 'svm'",
        examples=["logistic_regression"]
    )
    dataset: Optional[str] = Field(
        default="isot",
        description="Dataset to use for prediction: 'isot' or 'liar'",
        examples=["isot"]
    )


class PredictResponse(BaseModel):
    prediction: str = Field(..., description="Binary classification outcome: 'FAKE' or 'REAL'")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model prediction confidence score")
    model: str = Field(..., description="Name of the active machine learning classifier")
    probabilities: Dict[str, float] = Field(..., description="Class probability distribution for FAKE and REAL")
    wordCount: int = Field(..., description="Total word count analyzed")
    charCount: int = Field(..., description="Total character count analyzed")
    topTokens: Optional[List[str]] = Field(default=[], description="Top salient TF-IDF vocabulary tokens")
    explanation: str = Field(..., description="Linguistic and stylistic rationale generated by classifier")
    geminiInsights: Optional[Dict[str, Any]] = Field(default=None, description="Real-time Gemini AI credibility analysis")


class HealthResponse(BaseModel):
    status: str
    service: str
    active_model: str
    uptime_seconds: float


start_time = time.time()


# Lifespan Context Manager to load artifacts ONCE on startup
@asynccontextmanager
async def lifespan(app: FastAPI):
    print("------------------------------------------------------------------")
    print("🚀 Initializing FastAPI NLP Prediction Microservice...")
    predictor.load_models("isot")
    predictor.load_models("liar")
    print("📦 Models loaded in memory")
    print("------------------------------------------------------------------")
    yield
    print("🛑 Shutting down ML Microservice...")


app = FastAPI(
    title="Fake News Detection NLP Microservice",
    description="High-performance FastAPI service providing NLP inference for news verification using Scikit-learn and TF-IDF.",
    version="1.0.0",
    lifespan=lifespan
)

